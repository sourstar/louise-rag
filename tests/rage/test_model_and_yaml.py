def test_the_yaml_is_one_group_that_never_swaps_and_never_evicts(rage):
    text = swapyaml.render(model.load(rage.config))
    assert text == GOLDEN.format(m=rage.models.as_posix())
    assert "swap: false" in text and "exclusive: false" in text
    assert "preload" not in text, "the front preloads, through admission"
    assert text.count("ttl: 0") == 4, "idle is no reason to unload"


def test_a_weights_path_with_a_space_is_one_argument(rage, tmp_path):
    spaced = tmp_path / "my models"
    spaced.mkdir()
    rage.write_config("""\
[models.m]
engine  = {{ name = "llama.cpp", build = "b1" }}
weights = "%s/w.gguf"
device  = "cpu"
memory  = {{ cpu = 10 }}
cmd.cpu = ["/bin/s", "-m", "${{WEIGHTS}}", "--port", "${{PORT}}"]
""" % spaced.as_posix())
    line = swapyaml.command_line(model.load(rage.config).models["m"], "cpu")
    assert f"'{spaced.as_posix()}/w.gguf'" in line
    assert line.endswith("--port ${PORT}"), "${PORT} stays bare: it is llama-swap's macro"


BASE = """\
[models.m]
engine  = {{ name = "llama.cpp", build = "b1" }}
weights = "/models/w.gguf"
device  = "cpu"
memory  = {{ cpu = 10 }}
cmd.cpu = ["/bin/s", "-m", "${{WEIGHTS}}", "--port", "${{PORT}}"]
"""


@pytest.mark.parametrize("old, new, rule", [
    ('"--port", "${{PORT}}"]', '"--port=${{PORT}}"]', "exactly once"),
    ('"-m", "${{WEIGHTS}}", ', "", "exactly once"),
    ('"/bin/s"', '"s"', "absolute path"),
    ("memory  = {{ cpu = 10 }}", "memory  = {{ xpu = 10 }}", "memory.cpu"),
    ('device  = "cpu"', 'device  = "xpu"', "no command"),
    ('weights = "/models/w.gguf"', 'weights = "w.gguf"', "absolute path"),
    ('"--port", "${{PORT}}"]', '"--port", "${{PORT}}", "--host", "${{HOST}}"]', "placeholders"),
    ("[models.m]", "[models.m]\nenv = {{ PORT = \"${{PORT}}\" }}", "no placeholder is expanded"),
    ("[models.m]", "[models.m]\nttl = 60", "unknown key"),
])
def test_a_config_that_breaks_a_rule_is_refused_by_name(rage, old, new, rule):
    assert old in BASE
    rage.write_config(BASE.replace(old, new))
    with pytest.raises(RageConfigError, match=rule):
        model.load(rage.config)


def test_a_model_id_never_carries_a_device(rage):
    rage.write_config(BASE.replace("[models.m]", '[models."m@xpu"]'))
    with pytest.raises(RageConfigError, match="never '@'"):
        model.load(rage.config)


def test_a_preload_must_name_a_model(rage):
    rage.write_config('[rage]\npreload = ["ghost"]\n' + BASE)
    with pytest.raises(RageConfigError, match="ghost"):
        model.load(rage.config)


def test_the_api_writes_beside_the_operators_file_never_into_it(rage):
    """A PUT lands in rage.d/<id>.toml, whole. rage.toml is hand-written and
    commented, and is never rewritten."""
    before = rage.config.read_text()
    entry = model.entry_from_table("extra", {
        "engine": {"name": "llama.cpp", "build": "b1", "variant": None},
        "weights": "/models/extra.gguf", "device": "cpu", "memory": {"cpu": 300},
        "env": {"A": 'quote " and \\ slash'},
        "cmd": {"cpu": ["/bin/s", "-m", "${WEIGHTS}", "--port", "${PORT}"]}})
    drop = model.dropin_dir(rage.config)
    drop.mkdir()
    (drop / "extra.toml").write_text(model.entry_to_toml(entry), encoding="utf-8")
    cfg = model.load(rage.config)
    assert cfg.models["extra"].env == {"A": 'quote " and \\ slash'}, "round-trips"
    assert cfg.models["extra"].source.endswith("rage.d/extra.toml")
    assert model.entry_to_json(cfg.models["extra"])["cmd"]["cpu"][2] == "${WEIGHTS}"
    assert rage.config.read_text() == before


def test_one_id_in_both_places_is_an_error_not_a_silent_winner(rage):
    drop = model.dropin_dir(rage.config)
    drop.mkdir()
    (drop / "bge-m3.toml").write_text(
        model.entry_to_toml(model.load(rage.config).models["bge-m3"]), encoding="utf-8")
    with pytest.raises(RageConfigError, match="defined twice"):
        model.load(rage.config)
