"""`rage.toml` and the llama-swap yaml generated from it
(app/rage/model.py, app/rage/swapyaml.py; docs/notes/rage.md §4-5).

The yaml's one job is to make llama-swap policy-free. Its documented default
— a model in no group — is "only one model runs at a time across the entire
instance", so the first draft's "no groups" would have swapped every model
out for the next. One group, no swapping, no exclusivity.
"""
import pytest

from app.rage import model, swapyaml
from app.rage.model import RageConfigError


def test_a_config_loads_with_one_whole_command_per_device(rage):
    cfg = model.load(rage.config)
    assert sorted(cfg.models) == ["bge-m3", "madlad"]
    bge = cfg.models["bge-m3"]
    assert bge.devices == ("cpu", "xpu") and bge.device == "xpu"
    assert bge.engine.variant == "sycl"
    assert cfg.models["madlad"].engine.variant is None, "absent is null: TOML has none"
    assert bge.template("cpu")[-3:] == ("0", "--port", "${PORT}")
    assert bge.variant_id("cpu") == "bge-m3@cpu"
    assert cfg.reserve_mib == {"xpu": 1000, "cpu": 2000}


