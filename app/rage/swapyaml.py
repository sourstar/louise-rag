"""`rage.toml` → llama-swap's yaml. Generated, never edited by hand.

docs/notes/rage.md §4. llama-swap is the process runner and holds no
policy, which takes exactly one thing to say in its own language:

ONE GROUP, EVERY ENTRY IN IT, `swap: false`, `exclusive: false`. A model in
no group falls into llama-swap's default, which its example config spells
out: "only one model runs at a time across the entire instance". So the
policy-free configuration is not "no groups" — that one swaps — but one
group that never swaps and never evicts. `ttl: 0` and `globalTTL: 0`: idle
is no reason to unload (docs/notes/embedder-pool-spec.md §3). No preload
hook: the front preloads, through admission.

Every model is two entries where it has two devices, `<id>@xpu` and
`<id>@cpu`. They are internal: a collection's URL names the model, the
front routes to the variant that is up.

Written for llama-swap v256's schema (groups under
`routing.router.settings`). The image pins the version; a bump re-reads
this module against the new `docs/config.example.yaml`.

The strings are JSON, which is YAML: no indentation rule to get wrong and
no quoting rule of our own.
"""
from __future__ import annotations

import json
import shlex

from .model import PORT, WEIGHTS, ModelEntry, RageConfig

LLAMA_SWAP_VERSION = "v256"
GROUP = "rage"


def command_line(entry: ModelEntry, device: str) -> str:
    """The template as one shell-quoted line: llama-swap splits `cmd` as a
    shell would. `${PORT}` stays bare — it is llama-swap's macro, substituted
    before the split. `${WEIGHTS}` is ours, and is substituted here."""
    parts = []
    for arg in entry.template(device):
        if arg == PORT:
            parts.append(PORT)
        else:
            parts.append(shlex.quote(entry.weights if arg == WEIGHTS else arg))
    return " ".join(parts)


def render(cfg: RageConfig, *, health_timeout_s: int = 900, start_port: int = 10001) -> str:
    """`health_timeout_s` bounds a load: MADLAD takes 300 s to come up, and
    a load that never answers must end (CLAUDE.md: no wait without a bound)."""
    q = json.dumps
    out = [f"# generated by RAGE from rage.toml for llama-swap {LLAMA_SWAP_VERSION} "
           f"- never edit; edit rage.toml",
           f"healthCheckTimeout: {int(health_timeout_s)}",
           f"startPort: {int(start_port)}",
           "logLevel: info",
           "globalTTL: 0",
           "models:"]
    members: list[str] = []
    for model_id in sorted(cfg.models):
        entry = cfg.models[model_id]
        for device in entry.devices:
            variant = entry.variant_id(device)
            members.append(variant)
            out += [f"  {q(variant)}:",
                    f"    cmd: {q(command_line(entry, device))}",
                    f"    checkEndpoint: {q(entry.health)}",
                    "    ttl: 0",
                    "    unlisted: true"]
            if entry.env:
                out.append("    env:")
                out += [f"      - {q(f'{name}={value}')}"
                        for name, value in sorted(entry.env.items())]
    if not members:
        out[-1] = "models: {}"
    out += ["routing:",
            "  router:",
            "    use: group",
            "    settings:",
            "      groups:",
            f"        {q(GROUP)}:",
            "          swap: false",
            "          exclusive: false",
            "          persistent: true",
            "          members:" if members else "          members: []"]
    out += [f"            - {q(m)}" for m in members]
    return "\n".join(out) + "\n"
